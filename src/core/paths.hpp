#pragma once

// Пути к пользовательским файлам по XDG Base Directory.
//
// Здесь — каждый файл, который пишет приложение. Модули составляют имена
// только внутри каталога, которым владеют сами: кэш каталогов называет файлы
// хешем адреса источника, и это его дело.
//
// Переменные окружения читаются при каждом вызове, а не однажды при запуске:
// тесты подменяют их на свой временный каталог.

#include <QString>

namespace radio::paths {

// `~/.config/radio-player` — settings.json, overlay.json, state.json.
QString configDir();
// `~/.cache/radio-player` — кэш каталогов и обложек.
QString cacheDir();

QString settingsFile();
// Правки пользователя поверх каталогов.
QString overlayFile();
// Громкость, последняя станция, время последней проверки каталогов.
QString stateFile();

// Скачанные каталоги. Имена файлов внутри строит `catalog`: это его знание
// о том, чем он их различает.
QString catalogCacheDir();
QString artworkCacheDir();

// Сокет single-instance.
//
// В `$XDG_RUNTIME_DIR`, а не в общем `/tmp`, куда `QLocalServer` кладёт сокет
// по короткому имени: там он один на всю машину, и второй пользователь,
// запустив приложение, поднимал бы окно первому. Запасной путь тоже разведён
// по uid — на случай сеанса без runtime-каталога. Каталог создаётся.
QString ipcSocket();

// `.desktop`-файл автозапуска.
QString autostartFile();
// Как файл автозапуска назывался до перехода на reverse-DNS.
//
// Он остался у тех, кто включил автозапуск в ранних версиях, и продолжает
// работать сам по себе — поэтому его нужно убирать явно, иначе приложение
// будет запускаться дважды.
QString legacyAutostartFile();

// Создаёт каталоги, в которые приложение пишет. Идемпотентно.
void ensureDirs();

}  // namespace radio::paths
