#pragma once

// Чтение значений из JSON, которому нельзя доверять.
//
// Каталоги приходят из сети, оверлей и настройки — с диска, который мог
// поправить руками пользователь или другая версия приложения. Поле не того
// типа не должно ни ронять разбор, ни превращаться в мусор: каждое правило
// ниже повторяет то, как это поле понимала Python-версия, чтобы файлы,
// записанные ею, читались так же.

#include <QJsonValue>
#include <QString>

#include <optional>

namespace radio::json {

// Целое число. Дробное или нечисловое значение — не число: схему 1.5 или
// интервал «часто» разбирать наугад нельзя.
std::optional<qint64> integer(const QJsonValue &value);

// Текст поля: строка как есть, число — своей записью, всё остальное — пусто.
QString text(const QJsonValue &value);

// Истинность значения по правилам Python: пустое и нулевое — ложь.
bool truthy(const QJsonValue &value);

}  // namespace radio::json
