#pragma once

// Язык интерфейса: выбор и установка переводчиков.
//
// Исходные строки в коде английские, переводы встроены в программу (`:/i18n`).
// Язык берётся из настроек, `auto` означает системную локаль.
//
// Смена языка применяется при следующем запуске: Qt ставит собственный
// переводчик по системной локали ещё при создании приложения, и снять его потом
// нечем — кнопки стандартных диалогов остались бы на прежнем языке.

#include <QString>

class QCoreApplication;

namespace radio::i18n {

// Язык, который будет использован на самом деле: код из `LANGUAGES`.
QString resolve(const QString &language);

// Сообщает язык Qt через `LANGUAGE`. Вызывается **до** создания приложения:
// переменная влияет только на наш процесс.
QString prepare(const QString &language);

// Ставит переводчики приложения и Qt. Возвращает выбранный язык.
//
// Отсутствие файла перевода не ошибка: интерфейс останется на исходном
// английском, а приложение продолжит работать.
QString install(QCoreApplication *app, const QString &language);

}  // namespace radio::i18n
